/**
 * Build shareable weekly calendar CSV packs for Edge Esmeralda 2026.
 * Each week includes its sessions + adjacent weekend events from neighbor weeks
 * (same logic as loadEdgeEsmeraldaWeek in edge-esmeralda-2026.js), plus festival
 * and week-span long-term events.
 *
 * Outputs Yin-portal–compatible CSV under
 * internal/collaborations/edge-esmeralda-2026/shareable-weeks/.
 *
 * Run: node yang/web/circaevum/js/data/build-edge-esmeralda-shareable-weeks.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  buildShareableWeekPack,
  buildWeekSessions,
  edgeEventEndMs,
  edgeEventStartMs,
  loadRaw
} from './edge-esmeralda-build-core.mjs';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', '..', '..');
const OUT_DIR = join(REPO_ROOT, 'internal', 'collaborations', 'edge-esmeralda-2026', 'shareable-weeks');

function escapeCsvCell(s) {
  if (s == null) return '';
  const str = String(s);
  if (/[",\n\r]/.test(str)) return '"' + str.replace(/"/g, '""') + '"';
  return str;
}

function categoryOf(ev) {
  if (Array.isArray(ev.categories) && ev.categories[0]) return ev.categories[0];
  if (ev.category) return ev.category;
  return '';
}

function eventsToCsv(events) {
  const headers = ['Title', 'Category', 'Trip', 'Work', 'Start', 'End', 'Location', 'Description', 'URL', 'Color'];
  const rows = events.map((ev) => {
    const startMs = edgeEventStartMs(ev);
    const endMs = edgeEventEndMs(ev);
    const start = isFinite(startMs) ? new Date(startMs).toISOString() : '';
    const end = isFinite(endMs) ? new Date(endMs).toISOString() : '';
    return [
      escapeCsvCell(ev.summary),
      escapeCsvCell(categoryOf(ev)),
      '',
      '',
      escapeCsvCell(start),
      escapeCsvCell(end),
      escapeCsvCell(ev.location),
      escapeCsvCell(ev.description),
      escapeCsvCell(ev.url),
      escapeCsvCell(ev.color)
    ].join(',');
  });
  return [headers.join(','), ...rows].join('\r\n');
}

const raw = loadRaw();
const { weeks, occCount, sourceRows } = buildWeekSessions(raw, { descriptionMax: null });
mkdirSync(OUT_DIR, { recursive: true });

const manifestRows = [
  'Week,Slug,CalendarName,CSV,EventCount,SessionCount,WeekendExtraCount'
];

for (const w of [1, 2, 3, 4]) {
  const pack = buildShareableWeekPack(w, weeks);
  const base = pack.slug;
  const csvName = `${base}.csv`;
  const csvPath = join(OUT_DIR, csvName);

  writeFileSync(csvPath, eventsToCsv(pack.events));

  manifestRows.push(
    [
      w,
      pack.slug,
      escapeCsvCell(pack.calendarName),
      csvName,
      pack.eventCount,
      pack.sessionCount,
      pack.weekendExtraCount
    ].join(',')
  );

  console.log(
    `W${w} ${pack.calendarName}: ${pack.eventCount} events → ${csvName} (${pack.sessionCount} sessions + ${pack.weekendExtraCount} weekend bleed + ${pack.longTermCount} LTE)`
  );
}

writeFileSync(join(OUT_DIR, 'manifest.csv'), manifestRows.join('\r\n') + '\r\n');
writeFileSync(
  join(OUT_DIR, 'README.md'),
  `# Edge Esmeralda 2026 — shareable weekly calendars (CSV)

Generated by \`node yang/web/circaevum/js/data/build-edge-esmeralda-shareable-weeks.mjs\` from \`edge-esmeralda-2026-raw.json\`.

**Upload:** Yin-portal → **Import CSV/ICS** → pick the week file below.

| Week | CSV file | Theme |
|------|----------|--------|
| W1 | \`w1-protocols-for-flourishing.csv\` | Protocols for Flourishing (Jun 1–7) |
| W2 | \`w2-intelligence-autonomy.csv\` | Intelligence & Autonomy (Jun 8–14) |
| W3 | \`w3-emergent-futures.csv\` | Emergent Futures & World Building (Jun 15–21) |
| W4 | \`w4-environments-tomorrow.csv\` | Environments of Tomorrow (Jun 22–27) |

Columns match portal export: **Title, Category, Trip, Work, Start, End, Location, Description, URL, Color**.

Each file includes that week's sessions, adjacent weekend bleed from neighbor weeks, plus festival + week-span ribbons.

After import, name the layer, set visibility **public**, then share.

## Regenerate

\`\`\`bash
node yang/web/circaevum/js/data/build-edge-esmeralda-shareable-weeks.mjs
\`\`\`
`
);

console.log('Wrote', OUT_DIR);
console.log(`Source: ${sourceRows} rows → ${occCount} session occurrences`);
