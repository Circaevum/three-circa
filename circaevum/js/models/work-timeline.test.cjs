const assert = require('node:assert/strict');
const M = require('./work-timeline.js');
const VEvent = require('./vevent.js');
const event = M.seed()[2];
assert.deepEqual(new VEvent(event).toJSON().work, event.work, 'work metadata survives GL ingest and export');
assert.equal(new VEvent(event).validate().valid, true, 'work status must not replace RFC status');
assert.equal(M.normalize({uid:'hr',dtstart:event.dtstart,render:{kind:'timeseries'}}), null, 'Garmin series do not become work');
assert.equal(M.normalize({...event,dtstart:{dateTime:'invalid'}}),null);
assert.equal(M.normalize({...event,dtend:{dateTime:'2020-01-01'}}),null);
const milestone=M.normalize(M.seed().at(-1));
assert.equal(milestone.end,milestone.start);
const allDay=M.normalize({...event,dtstart:{date:'2026-11-06'},dtend:{date:'2026-11-07'}});
assert.equal(allDay.start,+new Date(2026,10,6), 'all-day time matches VEvent local dates');
assert.equal(M.pack([{start:0,end:2},{start:1,end:3},{start:3,end:4}])[1].row,1);
assert.equal(M.pack([{start:0,end:2},{start:1,end:3},{start:3,end:4}])[2].row,0);
assert.equal(M.pack([{start:0,end:1},{start:2,end:3}],4)[1].row,1,'readable cards cannot overlap');
assert.equal(M.dependencyState({dependencies:['missing']},[])[0].unresolved,true);
assert.equal(M.dependencyState({dependencies:['done']},[{id:'done',status:'done'}])[0].unresolved,false);
console.log('Work timeline: model, date, layout, dependencies, and Garmin isolation checks passed');
const mondayTicks=M.ticks(+new Date(2026,10,1),+new Date(2026,11,1),'month');
assert(mondayTicks.length>=4);
assert(mondayTicks.every(t=>new Date(t).getDay()===1),'month ticks must be calendar Mondays');
assert(mondayTicks.every(t=>new Date(t).getHours()===0),'weekly ticks survive DST at midnight');
assert.equal(M.semantic({...M.normalize(event),status:'waiting'}),'waiting');
assert.equal(M.semantic({...M.normalize(event),status:'done',kind:'milestone'}),'milestone-done');
assert.equal(M.semantic({...M.normalize(event),status:'planned',end:Date.now()+86400000}),'upcoming');
assert(M.cycle('a',['b'],[{id:'b',dependencies:['a']}]));
assert(!M.cycle('a',['b'],[{id:'b',dependencies:[]}]));
const meeting={...M.normalize(event),kind:'meeting',end:0,status:'planned',followUpAt:1};
assert(M.report([meeting],100)[0].noFollowUp);
assert(M.report([meeting],100)[0].followUpDue);
assert(!M.report([{...meeting,status:'no-outcome'}],100)[0].noFollowUp);
